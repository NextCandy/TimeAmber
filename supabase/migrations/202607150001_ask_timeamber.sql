create extension if not exists pg_trgm;

create table if not exists public.knowledge_documents (
  id bigint generated by default as identity primary key,
  post_id integer not null references public.posts(id) on delete cascade,
  source_type text not null check (source_type in ('blog', 'notion', 'web_archive')),
  content_origin text not null default 'post' check (
    content_origin in ('post', 'archive_html', 'archive_unavailable')
  ),
  title text not null,
  excerpt text not null default '',
  body text not null default '',
  category text not null default '',
  internal_url text,
  original_url text,
  source_created_at timestamptz,
  source_updated_at timestamptz,
  content_hash text not null default '',
  search_text text not null default '',
  search_vector tsvector not null default ''::tsvector,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (post_id)
);

create or replace function public.prepare_knowledge_document()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.title := left(coalesce(new.title, ''), 300);
  new.excerpt := left(coalesce(new.excerpt, ''), 1200);
  new.body := left(coalesce(new.body, ''), 180000);
  new.category := left(coalesce(new.category, ''), 200);
  new.search_text := lower(concat_ws(E'\n', new.title, new.excerpt, new.category, new.body));
  new.search_vector :=
    setweight(to_tsvector('simple', new.title), 'A') ||
    setweight(to_tsvector('simple', new.excerpt), 'B') ||
    setweight(to_tsvector('simple', new.category), 'B') ||
    setweight(to_tsvector('simple', new.body), 'C');
  new.content_hash := md5(
    concat_ws(E'\n', new.source_type, new.title, new.excerpt, new.body)
  );
  new.updated_at := now();
  return new;
end
$$;

drop trigger if exists knowledge_documents_prepare_search on public.knowledge_documents;
create trigger knowledge_documents_prepare_search
before insert or update of source_type, title, excerpt, body, category
on public.knowledge_documents
for each row execute function public.prepare_knowledge_document();

create or replace function public.knowledge_archive_url(value text)
returns text
language sql
immutable
parallel safe
as $$
  select nullif(
    (regexp_match(
      coalesce(value, ''),
      '<!--\s*timeamber-offline-html:v1\s+source:[a-z0-9_-]+\s+id:[0-9]+\s+url:([^\s>]+)\s*-->',
      'i'
    ))[1],
    ''
  );
$$;

create or replace function public.knowledge_original_url(value text)
returns text
language sql
immutable
parallel safe
as $$
  select nullif(
    (regexp_match(rtrim(coalesce(value, '')), '\((https?://[^)[:space:]]+)\)[[:space:]]*$', 'i'))[1],
    ''
  );
$$;

create or replace function public.refresh_knowledge_document_from_post()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  resolved_source_type text;
  resolved_internal_url text;
  resolved_original_url text;
begin
  resolved_source_type := case
    when new.slug like 'archive-%' then 'web_archive'
    when new.notion_id is not null or new.slug like 'notion-%' then 'notion'
    else 'blog'
  end;

  resolved_internal_url := case
    when resolved_source_type = 'web_archive'
      then coalesce(public.knowledge_archive_url(new.content), '/admin/posts/' || new.slug || '/edit')
    when new.published and (new.publish_at is null or new.publish_at <= now())
      then '/posts/' || new.slug
    else '/admin/posts/' || new.slug || '/edit'
  end;

  resolved_original_url := coalesce(
    nullif(new.external_url, ''),
    nullif(new.source, ''),
    public.knowledge_original_url(new.content)
  );

  insert into public.knowledge_documents (
    post_id,
    source_type,
    content_origin,
    title,
    excerpt,
    body,
    category,
    internal_url,
    original_url,
    source_created_at,
    source_updated_at
  ) values (
    new.id,
    resolved_source_type,
    'post',
    new.title,
    coalesce(new.excerpt, ''),
    coalesce(new.content, ''),
    coalesce(new.category, ''),
    resolved_internal_url,
    resolved_original_url,
    coalesce(new.publish_at, new.created_at),
    coalesce(new.source_updated_at, new.notion_last_edited, new.updated_at)
  )
  on conflict (post_id) do update set
    source_type = excluded.source_type,
    content_origin = case
      when excluded.source_type = 'web_archive'
        and public.knowledge_archive_url(excluded.body) is not null
        and public.knowledge_documents.content_origin in ('archive_html', 'archive_unavailable')
      then public.knowledge_documents.content_origin
      else excluded.content_origin
    end,
    title = excluded.title,
    excerpt = excluded.excerpt,
    body = case
      when excluded.source_type = 'web_archive'
        and public.knowledge_archive_url(excluded.body) is not null
        and public.knowledge_documents.content_origin in ('archive_html', 'archive_unavailable')
      then public.knowledge_documents.body
      else excluded.body
    end,
    category = excluded.category,
    internal_url = excluded.internal_url,
    original_url = coalesce(excluded.original_url, public.knowledge_documents.original_url),
    source_created_at = excluded.source_created_at,
    source_updated_at = excluded.source_updated_at;

  return new;
end
$$;

