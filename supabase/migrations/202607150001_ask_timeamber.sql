  coalesce(p.excerpt, ''),
  coalesce(p.content, ''),
  coalesce(p.category, ''),
  case
    when p.slug like 'archive-%'
      then coalesce(public.knowledge_archive_url(p.content), '/admin/posts/' || p.slug || '/edit')
    when p.published and (p.publish_at is null or p.publish_at <= now())
      then '/posts/' || p.slug
    else '/admin/posts/' || p.slug || '/edit'
  end,
  coalesce(
    nullif(p.external_url, ''),
    nullif(p.source, ''),
    public.knowledge_original_url(p.content)
