create or replace function public.search_timeamber_knowledge(
  query_text text,
  query_terms text[],
  result_limit integer default 8
)
returns table (
  post_id integer,
  source_type text,
  title text,
  excerpt text,
  body text,
  category text,
  internal_url text,
  original_url text,
  source_created_at timestamptz,
  score real,
  matched_terms text[]
)
language plpgsql
stable
security invoker
set search_path = public
as $$
declare
  normalized_query text := left(lower(trim(coalesce(query_text, ''))), 500);
  normalized_terms text[];
  text_query tsquery;
begin
  if not public.is_admin() then
    raise exception 'Administrator access required' using errcode = '42501';
  end if;

  select coalesce(array_agg(term), array[]::text[])
  into normalized_terms
  from (
    select distinct left(lower(trim(value)), 80) as term
    from unnest(coalesce(query_terms, array[]::text[])) as value
    where length(trim(value)) >= 2
    limit 12
  ) terms;

  if coalesce(array_length(normalized_terms, 1), 0) = 0 and normalized_query <> '' then
    normalized_terms := array[normalized_query];
  end if;

  text_query := websearch_to_tsquery('simple', array_to_string(normalized_terms, ' OR '));

  return query
  with matched_documents as materialized (
    select document.id
    from public.knowledge_documents document
    where document.search_vector @@ text_query

    union

    select document.id
    from unnest(normalized_terms) as search_term(term)
    join public.knowledge_documents document
      on document.search_text like '%' || search_term.term || '%'

    union

    select document.id
    from public.knowledge_documents document
    where
      similarity(lower(document.title), normalized_query) >= 0.12
      or similarity(lower(document.excerpt), normalized_query) >= 0.12
  ),
  scored as (
    select
      document.*,
      ts_rank_cd(document.search_vector, text_query) as fts_rank,
      greatest(
        similarity(lower(document.title), normalized_query),
        similarity(lower(document.excerpt), normalized_query),
        similarity(lower(document.category), normalized_query)
      ) as trigram_rank,
      term_stats.term_hits,
      term_stats.title_hits,
      term_stats.excerpt_hits,
      term_stats.matched_terms
    from matched_documents matched
    join public.knowledge_documents document on document.id = matched.id
    cross join lateral (
      select
        count(*) filter (where position(term in document.search_text) > 0)::integer as term_hits,
        count(*) filter (where position(term in lower(document.title)) > 0)::integer as title_hits,
        count(*) filter (where position(term in lower(document.excerpt)) > 0)::integer as excerpt_hits,
        coalesce(
          array_agg(term order by length(term) desc) filter (where position(term in document.search_text) > 0),
          array[]::text[]
        ) as matched_terms
      from unnest(normalized_terms) as term
    ) term_stats
  )
  select
    scored.post_id,
    scored.source_type,
    scored.title,
    scored.excerpt,
    scored.body,
    scored.category,
    scored.internal_url,
    scored.original_url,
    scored.source_created_at,
    (
      scored.title_hits * 4 +
      scored.excerpt_hits * 2 +
      scored.term_hits +
      scored.fts_rank * 4 +
      scored.trigram_rank * 2
    )::real as score,
    scored.matched_terms
  from scored
  where
    scored.term_hits > 0
    or scored.fts_rank > 0
    or scored.trigram_rank >= 0.12
  order by
    (
      scored.title_hits * 4 +
      scored.excerpt_hits * 2 +
      scored.term_hits +
      scored.fts_rank * 4 +
      scored.trigram_rank * 2
    ) desc,
    scored.source_created_at desc nulls last
  limit least(greatest(coalesce(result_limit, 8), 1), 20);
end
$$;

create or replace function public.get_timeamber_knowledge_status()
returns table (
  total bigint,
  blog bigint,
  notion bigint,
  web_archive bigint,
  archive_pending bigint
)
language plpgsql
stable
security invoker
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'Administrator access required' using errcode = '42501';
  end if;

  return query
  select
    count(*)::bigint,
    count(*) filter (where source_type = 'blog')::bigint,
    count(*) filter (where source_type = 'notion')::bigint,
    count(*) filter (where source_type = 'web_archive')::bigint,
    count(*) filter (
      where source_type = 'web_archive'
        and content_origin not in ('archive_html', 'archive_unavailable')
    )::bigint
  from public.knowledge_documents;
end
$$;

